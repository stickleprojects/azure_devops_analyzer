#!/usr/bin/env python3
"""Generate fixture repository seed JSON files from config.json."""

import json
from pathlib import Path

# Define paths
CONFIG_PATH = Path("tests/fixtures/scenarios/config.json")
GENERATED_DIR = Path("tests/fixtures/scenarios/generated/")

# Ensure the generated directory exists
GENERATED_DIR.mkdir(parents=True, exist_ok=True)

# Fallback list of repos if config.json is not found
FALLBACK_REPOS = [
    "python-docker",
    "go-microservice",
    "react-spa",
    "fullstack-monorepo",
    "java-maven-jenkins",
    "legacy-migration",
    "dual-ci",
    "python-dual-deps",
    "edge-case-empty",
    "deep-nested-manifests"
]

# Load config.json
try:
    with CONFIG_PATH.open("r") as f:
        config = json.load(f)
except FileNotFoundError:
    print(f"[ERROR] {CONFIG_PATH} not found. Using fallback list.", file=sys.stderr)
    config = {
        "repo_templates": {},
        "repo_sets": [{"template": repo} for repo in FALLBACK_REPOS]
    }

# Helper functions
def generate_file_names(repo_template):
    languages = repo_template.get("languages", [])
    file_names = []

    if "Python" in languages:
        file_names.extend([
            "README.md",
            "requirements.txt",
            "app.py",
            "tests/test_app.py",
            "config.yaml"
        ])
    if "TypeScript" in languages or "JavaScript" in languages:
        file_names.extend([
            "src/index.js",
            "public/index.html",
            "package.json",
            "tsconfig.json"
        ])
    if "Go" in languages:
        file_names.extend([
            "main.go",
            "cmd/main.go",
            "internal/handler.go",
            "Makefile"
        ])
    if "Java" in languages:
        file_names.extend([
            "pom.xml",
            "Jenkinsfile",
            "src/main/java/com/example/Example.java",
            "src/test/java/com/example/ExampleTest.java",
            ".mvn/wrapper/maven-wrapper.properties"
        ])
    if "C#" in languages:
        file_names.extend([
            "packages.config",
            "App.csproj",
            "app.config",
            "src/Program.cs",
            "tests/AppTests.cs",
            "bin/",
            "obj/"
        ])

    return list(set(file_names))  # Remove duplicates

def generate_manifests(repo_template):
    languages = repo_template.get("languages", [])
    manifests = {}

    if "Python" in languages:
        manifests["python"] = [
            {
                "type": "requirements.txt",
                "content": "# Python dependencies\nFlask==2.3.0\nrequests==2.31.0\npython-dotenv==1.0.0"
            }
        ]
    if "TypeScript" in languages:
        manifests["typescript"] = [
            {
                "type": "tsconfig.json",
                "content": "{\n  \"compilerOptions\": {\n    \"target\": \"es6\",\n    \"module\": \"commonjs\"\n  }\n}"
            }
        ]
    if "JavaScript" in languages:
        manifests["javascript"] = [
            {
                "type": "package.json",
                "content": "{\n  \"name\": \"example-app\",\n  \"version\": \"1.0.0\",\n  \"dependencies\": {\n    \"react\": \"^17.0.2\"\n  }\n}"
            }
        ]
    if "Go" in languages:
        manifests["go"] = [
            {
                "type": "go.mod",
                "content": "module example.com/example\n\ngo 1.16"
            },
            {
                "type": "go.sum",
                "content": "# go.sum\n# (generated by go mod tidy)\nexample.com/example v0.0.0-20230101000000-aabbccddeeff h1:abcdefg=\nexample.com/example v0.0.0-20230101000000-aabbccddeeff module example.com/example"
            }
        ]
    if "Java" in languages:
        manifests["java"] = [
            {
                "type": "pom.xml",
                "content": "<project xmlns=\"http://maven.apache.org/POM/4.0.0\" xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\"\n         xsi:schemaLocation=\"http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd\">\n  <modelVersion>4.0.0</modelVersion>\n\n  <groupId>com.example</groupId>\n  <artifactId>example-app</artifactId>\n  <version>1.0-SNAPSHOT</version>\n\n  <dependencies>\n    <dependency>\n      <groupId>junit</groupId>\n      <artifactId>junit</artifactId>\n      <version>4.12</version>\n      <scope>test</scope>\n    </dependency>\n  </dependencies>\n</project>"
            }
        ]
    if "C#" in languages:
        manifests["csharp"] = [
            {
                "type": "packages.config",
                "content": "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<packages>\n  <package id=\"Newtonsoft.Json\" version=\"13.0.1\" targetFramework=\"net472\" />\n</packages>"
            },
            {
                "type": ".csproj",
                "content": "<Project Sdk=\"Microsoft.NET.Sdk\">\n\n  <PropertyGroup>\n    <OutputType>Exe</OutputType>\n    <TargetFramework>net472</TargetFramework>\n  </PropertyGroup>\n\n  <ItemGroup>\n    <PackageReference Include=\"Newtonsoft.Json\" Version=\"13.0.1\" />\n  </ItemGroup>\n\n</Project>"
            }
        ]

    return manifests

def generate_branches(repo_template):
    base_branches = ["main", "develop"]
    pattern = repo_template.get("pattern", "")
    if pattern == "edge-case-empty":
        return base_branches
    elif pattern in ["fullstack-monorepo", "deep-nested-manifests"]:
        return base_branches + [f"feature/service-{i}" for i in range(1, 3)]
    else:
        return base_branches + [f"feature/{repo_template.get('name', '')}-{i}" for i in range(1, 2)]

# Generate seeds
seeds = []

for repo_set in config["repo_sets"]:
    template_name = repo_set["template"]
    repo_template = config["repo_templates"].get(template_name, {})

    if "names" in repo_set:
        names = repo_set["names"]
    elif "name_template" in repo_set and "services" in repo_set:
        names = [repo_set["name_template"].format(service=service) for service in repo_set["services"]]
    else:
        names = [template_name]

    for name in names:
        description = repo_set.get("description_template", "").format(service=name.split("-")[-1]) or repo_template.get("description", "")

        seed = {
            "name": name,
            "description": description,
            "languages": repo_template.get("languages", []),
            "file_names": generate_file_names(repo_template),
            "manifests": generate_manifests(repo_template),
            "branches": generate_branches(repo_template)
        }

        seeds.append(seed)

# Write seeds to files
for seed in seeds:
    file_path = GENERATED_DIR / f"{seed['name']}.json"
    with file_path.open("w") as f:
        json.dump(seed, f, indent=2)
    print(f"[OK] Created {file_path.name}")

print(f"[OK] Generated {len(seeds)} seed files")